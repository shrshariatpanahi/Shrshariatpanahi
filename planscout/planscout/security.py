"""Password hashing, token encryption and PKCE helpers."""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import secrets

from cryptography.fernet import Fernet

_SCRYPT_N, _SCRYPT_R, _SCRYPT_P = 2**14, 8, 1
MIN_PASSWORD_LENGTH = 10


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=_SCRYPT_N, r=_SCRYPT_R, p=_SCRYPT_P)
    return "$".join(
        ["scrypt", str(_SCRYPT_N), str(_SCRYPT_R), str(_SCRYPT_P), _b64(salt), _b64(digest)]
    )


def verify_password(password: str, stored: str) -> bool:
    try:
        scheme, n, r, p, salt, digest = stored.split("$")
    except ValueError:
        return False
    if scheme != "scrypt":
        return False
    candidate = hashlib.scrypt(password.encode(), salt=_unb64(salt), n=int(n), r=int(r), p=int(p))
    return hmac.compare_digest(candidate, _unb64(digest))


class TokenCipher:
    """Encrypts OAuth tokens at rest so a database leak does not expose carrier access.

    Takes a Fernet key, or any long random secret (e.g. one generated by a hosting provider), from
    which a Fernet key is derived.
    """

    def __init__(self, key: str):
        try:
            self._fernet = Fernet(key.encode())
        except ValueError:
            if len(key) < 32:
                raise ValueError("Encryption key must be a Fernet key or a random secret of at least 32 characters")
            self._fernet = Fernet(base64.urlsafe_b64encode(hashlib.sha256(key.encode()).digest()))

    @staticmethod
    def generate_key() -> str:
        return Fernet.generate_key().decode()

    def encrypt(self, payload: dict) -> bytes:
        return self._fernet.encrypt(json.dumps(payload).encode())

    def decrypt(self, ciphertext: bytes) -> dict:
        return json.loads(self._fernet.decrypt(ciphertext))


def new_pkce_pair() -> tuple[str, str]:
    """Return (code_verifier, S256 code_challenge) for an OAuth authorization request."""
    verifier = secrets.token_urlsafe(64)
    return verifier, pkce_challenge(verifier)


def pkce_challenge(verifier: str) -> str:
    return _b64(hashlib.sha256(verifier.encode()).digest())


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _unb64(data: str) -> bytes:
    return base64.urlsafe_b64decode(data + "=" * (-len(data) % 4))
